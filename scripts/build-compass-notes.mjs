// Writes compass-api/lib/course.js: the course's own words (every narration
// script, in page order) for Compass's system prompt. Run after changing
// narration-scripts.js:  node scripts/build-compass-notes.mjs
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, 'narration-scripts.js'), 'utf8'), ctx);
const narr = ctx.window.VVO_NARR || {};
const order = (fs.readFileSync(path.join(root, 'pager.js'), 'utf8').match(/key:'([a-z]+)'/g) || []).map((m) => m.slice(5, -1));
const keys = Object.keys(narr).sort((a, b) => {
  const ia = order.indexOf(a.split('/')[0]), ib = order.indexOf(b.split('/')[0]);
  return (ia < 0 ? 99 : ia) - (ib < 0 ? 99 : ib);
});
// spoken respellings back to their written form
const fix = (s) => s.replace(/Deer-myer/g, 'Diermeier').replace(/Kresh-eh-ray ow-day/g, 'Crescere aude').replace(/\bA I\b/g, 'AI');
const text = keys.map((k) => `[${k}] ${fix(narr[k])}`).join('\n');
const out = '// Generated by scripts/build-compass-notes.mjs from narration-scripts.js. Do not edit by hand.\nexport const COURSE_NOTES = ' + JSON.stringify(text) + ';\n';
fs.writeFileSync(path.join(root, 'compass-api', 'lib', 'course.js'), out);
console.log(`compass-api/lib/course.js: ${keys.length} sections, ${text.split(/\s+/).length} words`);
